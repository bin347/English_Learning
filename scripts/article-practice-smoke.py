import os, subprocess, tempfile
from pathlib import Path
from playwright.sync_api import expect, sync_playwright
root=Path(__file__).resolve().parents[1]
server_code="""import {startServer} from './server/index.mjs'; const s=await startServer({dataDir:process.env.SHIJU_TEST_DATA,staticDir:'frontend/dist'}); console.log(s.url);"""
with tempfile.TemporaryDirectory(prefix='shiju-article-ui-') as directory:
    env=os.environ.copy(); env['SHIJU_TEST_DATA']=directory
    proc=subprocess.Popen(['node','--input-type=module','-e',server_code],cwd=root,env=env,stdout=subprocess.PIPE,stderr=subprocess.PIPE,text=True)
    url=proc.stdout.readline().strip()
    try:
        with sync_playwright() as p:
            browser=p.chromium.launch(channel='msedge',headless=True)
            page=browser.new_page()
            fixture=page.request.post(url+'/api/books',data={'title':'Practice Fixture','format':'txt','text':'Mia found a small garden behind her house. Every morning, she watered the flowers and watched them grow.'}).json()
            page.goto(url,wait_until='networkidle')
            nav=page.locator('nav'); nav.get_by_role('button',name='句子练习').click()
            panel=page.locator('.practice-layout:visible')
            panel.get_by_role('button',name='整篇逐句练习').click()
            expect(panel.locator('.practice-prompt')).to_have_text('A small park stood between two busy streets.')
            panel.get_by_role('button',name='跳过 / 下一句').click()
            expect(panel.locator('.practice-prompt')).to_contain_text('For years')
            panel.locator('textarea').first.fill('我的答案'); panel.locator('textarea').first.blur()
            panel.get_by_label('选择文章').select_option('article-library')
            expect(panel.locator('.practice-prompt')).to_contain_text('When Lina')
            panel.get_by_label('选择文章').select_option('article-park')
            expect(panel.locator('.practice-prompt')).to_contain_text('For years')
            expect(panel.locator('textarea').first).to_have_value('我的答案')
            nav.get_by_role('button',name='听力').click(); listen=page.locator('.practice-layout:visible')
            listen.get_by_role('button',name='整篇逐句练习').click()
            listen.get_by_role('button',name='跳过 / 下一句').click(); listen.get_by_role('button',name='跳过 / 下一句').click()
            expect(listen.locator('.section-head').first).to_contain_text('第 3 句')
            page.wait_for_timeout(1000); page.reload(wait_until='networkidle')
            nav=page.locator('nav'); nav.get_by_role('button',name='句子练习').click(); panel=page.locator('.practice-layout:visible')
            expect(panel.get_by_role('button',name='整篇逐句练习')).to_have_attribute('aria-pressed','true')
            expect(panel.locator('.practice-prompt')).to_contain_text('For years'); expect(panel.locator('textarea').first).to_have_value('我的答案')
            nav.get_by_role('button',name='听力').click(); listen=page.locator('.practice-layout:visible')
            expect(listen.locator('.section-head').first).to_contain_text('第 3 句')
            nav.get_by_role('button',name='句子练习').click(); panel=page.locator('.practice-layout:visible')
            panel.get_by_role('button',name='提交答案',exact=True).click()
            expect(panel.locator('.feedback')).to_be_visible()
            page.wait_for_timeout(800); page.reload(wait_until='networkidle')
            nav=page.locator('nav'); nav.get_by_role('button',name='句子练习').click(); panel=page.locator('.practice-layout:visible')
            expect(panel.locator('textarea').first).to_have_value('我的答案')
            panel.get_by_role('button',name='查看反馈').click()
            expect(panel.locator('.feedback')).to_be_visible()
            panel.get_by_role('button',name='收起反馈',exact=True).first.click()
            example=next(e for e in page.request.get(url+'/api/bootstrap').json()['exercises'] if not e.get('articleId'))
            def catalog(route):
                if route.request.method=='GET': route.fulfill(json={'results':[example]})
                else: route.fulfill(json=example)
            page.route('**/api/exercise-catalog**',catalog)
            panel.get_by_text('在线搜索例句').click()
            panel.get_by_label('在线例句搜索').fill('rain')
            panel.get_by_role('button',name='搜索例句').click()
            panel.get_by_role('button',name='加入练习').click()
            expect(panel.get_by_role('button',name='单句练习')).to_have_attribute('aria-pressed','true')
            expect(panel.locator('.practice-prompt')).to_have_text(example['text'])
            panel.get_by_role('button',name='整篇逐句练习').click()
            panel.get_by_text('从书架创建文章练习').click()
            panel.get_by_label('选择书架文本').select_option(fixture['id'])
            panel.get_by_role('button',name='创建逐句练习').click()
            expect(panel.locator('.practice-prompt')).to_contain_text('Mia found')
            panel.locator('textarea').first.fill('米娅发现了花园')
            panel.get_by_role('button',name='提交答案',exact=True).click()
            expect(panel.locator('.feedback')).to_contain_text('暂不提供分数')
            panel.get_by_role('button',name='原文对照').click()
            page.route('**/api/translate',lambda route: route.fulfill(json={'provider':'dictionary','translation':'garden：花园'}))
            panel.get_by_role('button',name='查看辅助翻译').click()
            expect(panel.locator('.feedback')).to_contain_text('本地词典逐词释义')
            expect(panel.locator('.feedback')).to_contain_text('garden：花园')
            browser.close()
        print('Article switching, independent progress and draft resume passed.')
    finally:
        proc.terminate(); proc.wait(timeout=10)
